package main

import (
	"fmt"
	"strings"
)

const (
	cubeAssertsPath = "../c64port/src/cube_asserts.inc"
	cubeLayoutPath  = "../c64port/src/cube_layout.inc"
)

type cubeArea struct {
	constant string
	slots    int
	symbol   string
}

// Where the images wait for the scene, in the order they are built (see cube_build.s)
var cubeAreas = []cubeArea{
	{"CUBE_HIGH_SLOTS", 44, "CUBE_HIGH_IMAGES"},
	{"CUBE_TILE_FREE_SLOTS", 20, "CUBE_TILE_FREE"},
	{"CUBE_CHARSET_SLOTS", 12, "CUBE_CHARSET_FREE"},
	{"CUBE_CHAR_SLOT_IMAGES", 15, "CUBE_CHAR_SLOTS"},
	{"CUBE_SPRITE_SLOT_IMAGES", 19, "CUBE_SPRITE_BLOCKS"},
}

// The images are built in the order the scene needs them: 0, then 2 to 109, then 1
func cubeSlotImage(slot int) int {
	switch {
	case slot == 0:
		return 0
	case slot == cubeImageCount-1:
		return 1
	}
	return slot + 1
}

func writeCubeLayout() {
	var constants, asserts strings.Builder
	constants.WriteString("; Generated by proto (go run -C proto . cube), do not edit\n; The number of images in each area of memory (see cube_areas in proto/cube_layout.go)\n\n")
	asserts.WriteString("; Generated by proto (go run -C proto . cube), do not edit\n; The golden image file against every area of memory, once all images are built\n")
	slot := 0
	for _, area := range cubeAreas {
		fmt.Fprintf(&constants, "%s = %d\n", area.constant, area.slots)
		for start := 0; start < area.slots; {
			end := start + 1
			for end < area.slots && cubeSlotImage(slot+end) == cubeSlotImage(slot+end-1)+1 {
				end++
			}
			address := area.symbol
			if start > 0 {
				address = fmt.Sprintf("%s + %d", area.symbol, start*cubeImageBytes)
			}
			file := `"../proto/golden/cube_images.bin"`
			if image := cubeSlotImage(slot + start); image > 0 {
				file = fmt.Sprintf("%s + %d", file, image*cubeImageBytes)
			}
			fmt.Fprintf(&asserts, "    assert_if CUBE_BUILT, %d, %s, %s, %d\n", cubeImageCount, address, file, (end-start)*cubeImageBytes)
			start = end
		}
		slot += area.slots
	}
	if slot != cubeImageCount {
		fmt.Printf("Warning: the areas hold %d images, not %d\n", slot, cubeImageCount)
	}
	for path, text := range map[string]string{cubeLayoutPath: constants.String(), cubeAssertsPath: asserts.String()} {
		if err := writeTextFile(path, text); err != nil {
			fmt.Printf("Warning: failed to write %s: %v\n", path, err)
		}
	}
	fmt.Printf("Exported %s and %s\n", cubeLayoutPath, cubeAssertsPath)
}
