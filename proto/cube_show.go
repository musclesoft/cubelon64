package main

import (
	"fmt"
	"strings"
)

const (
	cubeShowDataPath   = "../c64port/src/cube_show_data.inc"
	cubeShowBlocks     = 8
	cubeShowCharsBase  = 0x6000 + 192
	cubeShowCodeBase   = 24
	cubeShowRings      = 4
	cubeShowSlots      = 32
	cubeShowCharsBytes = 50
	cubeShowSpriteRow  = 9
)

var cubeShowPieceOffsets = [3]int{0, 16, 34}
var cubeShowPieceLengths = [3]int{16, 18, 16}

func cubeRingOfBlock(row, column int) int {
	nearest := min(min(row, cubeShowBlocks-1-row), min(column, cubeShowBlocks-1-column))
	return 3 - nearest
}

// The chars of a block's row: 3 per block, code 24 + 12 * column + 3 * ring + row of the tile
func cubeScreenCodes(gridRow int) []int {
	tileRow, tileLine := gridRow/3, gridRow%3
	var codes []int
	for column := 0; column < cubeShowBlocks; column++ {
		for char := 0; char < 3; char++ {
			codes = append(codes, cubeShowCodeBase+12*char+3*cubeRingOfBlock(tileRow, column)+tileLine)
		}
	}
	return codes
}

func writeCubeShowData() {
	var out strings.Builder
	out.WriteString("; Generated by proto (go run -C proto . cube), do not edit\n")
	out.WriteString("; The unrolled and tabled parts of cube_show.s: the screen's codes, the sprite pointers of each ring,\n")
	out.WriteString("; the chars' copy into each ring and the ring buffer's slot addresses\n\n")
	cubeShowWriteScreen(&out)
	cubeShowWritePointers(&out)
	cubeShowWriteCharCopies(&out)
	cubeShowWriteTables(&out)
	if err := writeTextFile(cubeShowDataPath, out.String()); err != nil {
		fmt.Printf("Warning: failed to write %s: %v\n", cubeShowDataPath, err)
		return
	}
	fmt.Printf("Exported %s\n", cubeShowDataPath)
}

func cubeShowWriteScreen(out *strings.Builder) {
	out.WriteString(`; Write the codes of the next 4 tile rows of the grid into screen A, a table row for the 3 lines of a
; tile row with the line added: the two steps of the switch take a frame each
.proc cube_write_screen
    ldx CUBE_SCREEN_STEP
    lda screen_start_low,x
    sta CUBE_SHOW_DST
    lda screen_start_high,x
    sta CUBE_SHOW_DST + 1
    lda screen_first_code,x
    tax
    clc
    adc #96
    sta CUBE_SCREEN_END
@tile_row:
    lda #0
    sta CUBE_LINE
@line:
    stx CUBE_ROW_START
    lda CUBE_SHOW_DST
    sta @store + 1
    lda CUBE_SHOW_DST + 1
    sta @store + 2
    ldy #0
@code:
    lda cube_screen_codes,x
    clc
    adc CUBE_LINE
@store:
    sta $FFFF,y
    inx
    iny
    cpy #24
    bne @code
    ldx CUBE_ROW_START
    lda CUBE_SHOW_DST
    clc
    adc #40
    sta CUBE_SHOW_DST
    bcc @same_page
    inc CUBE_SHOW_DST + 1
@same_page:
    inc CUBE_LINE
    lda CUBE_LINE
    cmp #3
    bne @line
    txa
    clc
    adc #24
    tax
    cpx CUBE_SCREEN_END
    bne @tile_row
    inc CUBE_SCREEN_STEP
    rts
.endproc

screen_start_low:
    .byte <GRID_ORIGIN, <CUBE_SCREEN_SECOND
screen_start_high:
    .byte >GRID_ORIGIN, >CUBE_SCREEN_SECOND
screen_first_code:
    .byte 0, 96

`)
}

func cubeShowWritePointers(out *strings.Builder) {
	var byRing [cubeShowRings][]int
	for sprite := 0; sprite < cubeShowBlocks; sprite++ {
		for band := 0; band < cubeShowBlocks; band++ {
			ring := cubeRingOfBlock(band, sprite)
			byRing[ring] = append(byRing[ring], 8*sprite+band)
		}
	}
	out.WriteString("; Point the sprites of every band at the sprite block of their ring\n")
	out.WriteString("; The pointers of the first band are also written into screen A: the interrupt that sets them for the\n")
	out.WriteString("; next frame came before this step.\n.proc point_sprites\n")
	for ring, indexes := range byRing {
		fmt.Fprintf(out, "    lda CUBE_RING_POINTER + %d\n", ring)
		for _, index := range indexes {
			fmt.Fprintf(out, "    sta SIMPLE_POINTERS + %d\n", index)
		}
		if ring == cubeShowRings-1 {
			for sprite := 0; sprite < cubeShowBlocks; sprite++ {
				fmt.Fprintf(out, "    sta POINTERS_A + %d\n", sprite)
			}
		}
	}
	out.WriteString("    rts\n.endproc\n\n")
}

func cubeShowWriteCharCopies(out *strings.Builder) {
	for ring := 0; ring < cubeShowRings; ring++ {
		destinations := [3]int{
			cubeShowCharsBase + 24*ring + 4,
			cubeShowCharsBase + 96 + 24*ring + 3,
			cubeShowCharsBase + 192 + 24*ring + 4,
		}
		fmt.Fprintf(out, "; Copy the chars at CUBE_SHOW_SRC into the chars of ring %d\n.proc copy_chars_%d\n", ring, ring)
		for piece, destination := range destinations {
			out.WriteString("    lda CUBE_SHOW_SRC\n")
			if offset := cubeShowPieceOffsets[piece]; offset > 0 {
				fmt.Fprintf(out, "    clc\n    adc #%d\n", offset)
			}
			fmt.Fprintf(out, "    sta @piece%d + 1\n    lda CUBE_SHOW_SRC + 1\n", piece)
			if cubeShowPieceOffsets[piece] > 0 {
				out.WriteString("    adc #0\n")
			}
			fmt.Fprintf(out, "    sta @piece%d + 2\n    ldy #%d\n@piece%d:\n    lda $FFFF,y\n    sta $%04X,y\n    dey\n    bpl @piece%d\n",
				piece, cubeShowPieceLengths[piece]-1, piece, destination, piece)
		}
		out.WriteString("    rts\n.endproc\n\n")
	}
}

func cubeShowWriteTables(out *strings.Builder) {
	out.WriteString("copy_chars_entries:\n    .word copy_chars_0 - 1, copy_chars_1 - 1, copy_chars_2 - 1, copy_chars_3 - 1\n\n")
	var chars, sprites []string
	for slot := 0; slot < cubeShowSlots; slot++ {
		chars = append(chars, fmt.Sprintf("CUBE_CHAR_SLOTS + %d", cubeShowCharsBytes*slot))
		sprites = append(sprites, fmt.Sprintf("CUBE_SPRITE_BLOCKS + %d", 64*slot+cubeShowSpriteRow))
	}
	fmt.Fprintf(out, "char_slot_address:\n    .word %s\n", strings.Join(chars, ", "))
	fmt.Fprintf(out, "sprite_slot_address:\n    .word %s\n\n", strings.Join(sprites, ", "))
	out.WriteString("cube_screen_codes:\n")
	for tileRow := 0; tileRow < cubeShowBlocks; tileRow++ {
		var codes []string
		for _, code := range cubeScreenCodes(3 * tileRow) {
			codes = append(codes, fmt.Sprint(code))
		}
		fmt.Fprintf(out, "    .byte %s\n", strings.Join(codes, ", "))
	}
}
