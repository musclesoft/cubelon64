const (
	mergeLastState     = 20
	mergeFirstFrame    = 2679
	mergeSquareFrame   = 2619
	mergeShrinkEnd     = 14
	mergeStart         = 8.0
	mergeShrinkSpeed   = 0.5
	mergeMoveX         = -0.75
	mergeMoveY         = 0.25
	mergePieceDistance = 3.0
	mergeDataPath      = "../c64port/src/merge_data.inc"
	mergeImagesPath    = "golden/merge_images.bin"
	mergeComparePath   = "golden/merge_compare.png"
)

// The last scene of the animation: the large square, which is a square of 8 pixels in each of the four
// corners of every cell, divides into these four squares, each of which shrinks by half a pixel a state and
// moves on a straight line, the four of them turned by a quarter turn about the centre of the cell
// (the first one from the top right corner to the left of the top, and so on), until they are a pixel
// large. From then on four squares grow in the cell, at the same places, at a pixel a state, and merge into
// the square of 12 pixels of the marching cubes' last picture.
//
// The squares as centre and size, relative to the centre of the cell
func mergeSquares(state int) [4][3]float64 {
	var squares [4][3]float64
	if state > mergeShrinkEnd {
		size := float64(state - mergeShrinkEnd)
		for i, sign := range [4][2]float64{{-1, -1}, {1, -1}, {-1, 1}, {1, 1}} {
			squares[i] = [3]float64{sign[0] * mergePieceDistance, sign[1] * mergePieceDistance, size}
		}
		return squares
	}
	t := float64(state)
	x, y := mergeStart+mergeMoveX*t, -mergeStart+mergeMoveY*t
	size := mergeStart - mergeShrinkSpeed*t
	for i := range squares {
		squares[i] = [3]float64{x, y, size}
		x, y = y, -x
	}
	return squares
}

// The tile of the even cells: the tile at diamondOrigin
func mergeTile(state int) morphCoverage {
	var polygons []morphKite
	for _, square := range mergeSquares(state) {
		centreX := float64(diamondOrigin+morphTileSize/2) + square[0]
		centreY := float64(diamondOrigin+morphTileSize/2) + square[1]
		half := square[2] / 2
		polygons = append(polygons, morphKite{
			{centreX - half, centreY - half}, {centreX + half, centreY - half},
			{centreX + half, centreY + half}, {centreX - half, centreY + half},
		})
	}
	return diamondTile(polygons, diamondOrigin, diamondOrigin)
}

func runMerge() {
	var screens [mergeLastState/diamondStateStep + 1]referenceScreen
	for index := range screens {
		var err error
		if screens[index], err = loadReferenceScreen(mergeFrameOfState(diamondStateStep * index)); err != nil {
			fmt.Printf("No ZX reference: %v\n", err)
			return
		}
	}
	var all [mergeLastState + 1]morphCoverage
	total, oddMismatches := 0, 0
	for state := range all {
		all[state] = mergeTile(state)
	}
	for index := range screens {
		state := diamondStateStep * index
		diff := countMorphDiff(fullMorphTile(all[state]), screens[index].tile(diamondOrigin, diamondOrigin))
		mismatches := countTileMismatches(all[state], &screens[index], diamondOrigin, diamondOrigin)
		oddMismatches += countTileMismatches(all[state], &screens[index], diamondOrigin+morphTileSize, diamondOrigin)
		total += diff
		fmt.Printf("state %2d: %2d pixels differ from the ZX tile, %d frame mismatches\n", state, diff, mismatches)
	}
	fmt.Printf("Merge tiles: %d pixels differ in total; the neighbouring cell, which shows the same tile, has %d frame mismatches\n", total, oddMismatches)

	writeMergeComparison(&screens, &all)
	writeMergeImages(&all)
	writeMergeData(&all)
}

// The ZX frame of an even state; the state 0 is the large square, held
func mergeFrameOfState(state int) int {
	if state == 0 {
		return mergeSquareFrame
	}
	return mergeFirstFrame + state
}

// The states 1-20 as the C64 holds them: the tile of every state, which the cells of both kinds of
// the checkerboard show alike
func writeMergeImages(all *[mergeLastState + 1]morphCoverage) {
	images := all[1:]
	if err := writeTileImages(mergeImagesPath, images); err != nil {
		fmt.Printf("Warning: failed to write %s: %v\n", mergeImagesPath, err)
		return
	}
	fmt.Printf("Exported %s (%d states, %d bytes each)\n", mergeImagesPath, mergeLastState, imageBytes)
}

// The tile has quarter turn symmetry like the diamonds' tile, so its top left quarter is enough
func writeMergeData(all *[mergeLastState + 1]morphCoverage) {
	var out strings.Builder
	out.WriteString("; Generated by proto (go run . merge), do not edit\n")
	out.WriteString("; The tiles of the last scene's states 1-20, each as its top left quarter, like diamond_data.inc\n\n")
	out.WriteString(".segment \"TILEDATA\"\n\n")
	out.WriteString(".export merge_quarter_tiles\nmerge_quarter_tiles:\n")
	bytes := 0
	for state := 1; state <= mergeLastState; state++ {
		packed := packMorphCoverage(all[state])
		quarter := diamondQuarterTile(packed)
		if got := expandDiamondQuarter(quarter); string(got) != string(packed) {
			fmt.Printf("Warning: the quarter of state %d does not rebuild its tile\n", state)
		}
		fmt.Fprintf(&out, "    ; state %d\n", state)
		for row := 0; row < diamondHalfRows; row++ {
			fmt.Fprintf(&out, "    .byte $%02X, $%02X, $%02X\n", quarter[3*row], quarter[3*row+1], quarter[3*row+2])
			bytes += 3
		}
	}
	if err := writeTextFile(mergeDataPath, out.String()); err != nil {
		fmt.Printf("Warning: failed to write %s: %v\n", mergeDataPath, err)
		return
	}
	fmt.Printf("Exported %s (%d bytes of data)\n", mergeDataPath, bytes)
}

func writeMergeComparison(screens *[mergeLastState/diamondStateStep + 1]referenceScreen, all *[mergeLastState + 1]morphCoverage) {
	const gap = 4
	cell := morphTileSize * morphScale
	img := image.NewRGBA(image.Rect(0, 0, len(all)*(cell+gap)-gap, 3*(cell+gap)-gap))
	fillMorphRect(img, img.Rect, color.RGBA{R: 40, G: 60, B: 160, A: 255})
	for state := range all {
		left := state * (cell + gap)
		drawMorphCoverage(img, left, cell+gap, all[state])
		if state%diamondStateStep == 0 {
			reference := screens[state/diamondStateStep].tile(diamondOrigin, diamondOrigin)
			drawMorphReference(img, left, 0, reference)
			drawMorphDiff(img, left, 2*(cell+gap), reference, fullMorphTile(all[state]))
		}
	}
	file, err := os.Create(mergeComparePath)
	if err != nil {
		fmt.Printf("Warning: failed to create %s: %v\n", mergeComparePath, err)
		return
	}
	defer file.Close()
	if err := png.Encode(file, img); err != nil {
		fmt.Printf("Warning: failed to encode %s: %v\n", mergeComparePath, err)
		return
	}
	fmt.Printf("Exported %s (rows: ZX reference, tile as the C64 shows it, difference; one column per 50 Hz state 0-20, the ZX demo shows the even ones)\n", mergeComparePath)
}
