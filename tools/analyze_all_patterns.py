#!/usr/bin/env python3
"""
Analyze all 10 patterns to understand the generation algorithm.
"""

from test_pivot_18_15 import load_raw_pattern, bitmap_to_string

frames = [318, 320, 322, 324, 326, 328, 330, 332, 334, 336]

print("Analyzing all 10 unique patterns")
print("=" * 70)

for frame in frames:
    filename = f"../emulator/frames/raw_frame{frame}.txt"
    pixels = load_raw_pattern(filename)

    # Find bounding box
    min_x, max_x = 24, -1
    min_y, max_y = 24, -1
    total_pixels = 0

    for y, row in enumerate(pixels):
        for x, pixel in enumerate(row):
            if pixel:
                total_pixels += 1
                min_x = min(min_x, x)
                max_x = max(max_x, x)
                min_y = min(min_y, y)
                max_y = max(max_y, y)

    width = max_x - min_x + 1 if max_x >= min_x else 0
    height = max_y - min_y + 1 if max_y >= min_y else 0

    # Check wrapping
    left_pixels = sum(1 for row in pixels for x, p in enumerate(row) if p and x < 4)
    right_pixels = sum(1 for row in pixels for x, p in enumerate(row) if p and x >= 20)
    wrapped = left_pixels > 0 and right_pixels > 0

    # Check pixel density
    if width > 0 and height > 0:
        bbox_area = width * height
        fill_ratio = total_pixels / bbox_area
    else:
        fill_ratio = 0

    print(f"\nFrame {frame}:")
    print(f"  BBox: ({min_x},{min_y}) to ({max_x},{max_y}) = {width}×{height}")
    print(f"  Pixels: {total_pixels}, Fill ratio: {fill_ratio:.2%}")
    print(f"  Wrapped: {'YES' if wrapped else 'NO'}")

    # Show the pattern
    print("  Pattern:")
    for y, row in enumerate(pixels):
        if y < min_y or y > max_y:
            continue
        line = "    "
        for x, pixel in enumerate(row):
            line += "█" if pixel else "·"
        print(line)

print("\n" + "=" * 70)
print("Analysis:")
print("- Frame 336: Two vertical bars (axis-aligned)")
print("- Other frames: Appear to be rotated versions")
print("- All patterns fit in roughly 12-16 pixel square")
print("- Consistent fill ratio suggests same shape rotated")
print("\nConclusion: Patterns were likely generated by rotating a square")
print("and pre-rendering 10 keyframes for the animation cycle.")
