#!/usr/bin/env python3
"""
Generate a test charset with recognizable patterns
"""

def generate_test_charset():
    """Generate 256 8x8 tiles with test patterns"""

    tiles = []

    # Tile 0: Blank
    tiles.append([0x00] * 8)

    # Tile 1: Checkerboard 1
    tiles.append([0xAA, 0x55, 0xAA, 0x55, 0xAA, 0x55, 0xAA, 0x55])

    # Tile 2: Checkerboard 2 (inverse)
    tiles.append([0x55, 0xAA, 0x55, 0xAA, 0x55, 0xAA, 0x55, 0xAA])

    # Tile 3: Horizontal stripes
    tiles.append([0xFF, 0x00, 0xFF, 0x00, 0xFF, 0x00, 0xFF, 0x00])

    # Tile 4: Vertical stripes
    tiles.append([0xCC] * 8)

    # Tile 5: Diagonal 1
    tiles.append([0x80, 0x40, 0x20, 0x10, 0x08, 0x04, 0x02, 0x01])

    # Tile 6: Diagonal 2
    tiles.append([0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80])

    # Tile 7: Dots
    tiles.append([0x88, 0x00, 0x22, 0x00, 0x88, 0x00, 0x22, 0x00])

    # Tile 8: Cross
    tiles.append([0x18, 0x18, 0xFF, 0xFF, 0x18, 0x18, 0x18, 0x18])

    # Tile 9: Border (for animation)
    tiles.append([0xFF, 0x81, 0x81, 0x81, 0x81, 0x81, 0x81, 0xFF])

    # Tile 10: Filled border (for animation)
    tiles.append([0xFF, 0xFF, 0xC3, 0xC3, 0xC3, 0xC3, 0xFF, 0xFF])

    # Tiles 11-31: Gradients and patterns
    for i in range(11, 32):
        if i < 20:
            # Gradient
            val = (i - 11) * 16
            tiles.append([val] * 8)
        else:
            # Random-ish pattern based on index
            pattern = []
            for j in range(8):
                pattern.append(((i * 7 + j * 13) ^ (i + j)) & 0xFF)
            tiles.append(pattern)

    # Tile 32: Space (blank)
    tiles.append([0x00] * 8)

    # Tiles 33-159: Fill with test patterns
    for i in range(33, 160):
        pattern = []
        for j in range(8):
            # Create varied patterns
            val = ((i + j) * 17) & 0xFF
            pattern.append(val)
        tiles.append(pattern)

    # Tile 160: Solid block
    tiles.append([0xFF] * 8)

    # Tiles 161-255: More test patterns
    for i in range(161, 256):
        pattern = []
        for j in range(8):
            val = ((i - j) * 23) & 0xFF
            pattern.append(val)
        tiles.append(pattern)

    return tiles

def write_charset_asm(tiles, filename):
    """Write tiles as ca65 assembly"""
    with open(filename, 'w') as f:
        f.write("; Test charset with recognizable patterns\n")
        f.write("; Generated by generate_test_charset.py\n")
        f.write("\n")
        f.write(".export pattern_charset\n")
        f.write("\n")
        f.write("pattern_charset:\n")

        for i, tile in enumerate(tiles):
            if i % 8 == 0:
                f.write(f"\n; Tiles {i}-{min(i+7, 255)}\n")

            bytes_str = ", ".join(f"${b:02X}" for b in tile)
            f.write(f".byte {bytes_str}  ; tile {i}\n")

        f.write("\n")

if __name__ == '__main__':
    tiles = generate_test_charset()
    write_charset_asm(tiles, 'src/data/pattern_charset_test.s')
    print(f"Generated {len(tiles)} test tiles in pattern_charset_test.s")
    print("Tile 0: Blank")
    print("Tile 1: Checkerboard")
    print("Tile 2: Checkerboard (inverse)")
    print("Tiles 3-10: Various test patterns")
    print("Tile 32: Space")
    print("Tile 160: Solid block")
