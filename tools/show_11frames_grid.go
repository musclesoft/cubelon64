func drawDigit(img *image.RGBA, x, y, digit int) {
	// Simple 5x7 bitmap font for digits 0-9
	digits := [10][7]uint8{
		// 0
		{0b01110, 0b10001, 0b10011, 0b10101, 0b11001, 0b10001, 0b01110},
		// 1
		{0b00100, 0b01100, 0b00100, 0b00100, 0b00100, 0b00100, 0b01110},
		// 2
		{0b01110, 0b10001, 0b00001, 0b00010, 0b00100, 0b01000, 0b11111},
		// 3
		{0b01110, 0b10001, 0b00001, 0b00110, 0b00001, 0b10001, 0b01110},
		// 4
		{0b00010, 0b00110, 0b01010, 0b10010, 0b11111, 0b00010, 0b00010},
		// 5
		{0b11111, 0b10000, 0b11110, 0b00001, 0b00001, 0b10001, 0b01110},
		// 6
		{0b00110, 0b01000, 0b10000, 0b11110, 0b10001, 0b10001, 0b01110},
		// 7
		{0b11111, 0b00001, 0b00010, 0b00100, 0b01000, 0b01000, 0b01000},
		// 8
		{0b01110, 0b10001, 0b10001, 0b01110, 0b10001, 0b10001, 0b01110},
		// 9
		{0b01110, 0b10001, 0b10001, 0b01111, 0b00001, 0b00010, 0b01100},
	}

	if digit < 0 || digit > 9 {
		return
	}

	pattern := digits[digit]
	for row := 0; row < 7; row++ {
		for col := 0; col < 5; col++ {
			if (pattern[row]>>(4-col))&1 == 1 {
				img.Set(x+col, y+row, color.RGBA{0, 0, 0, 255})
			}
		}
	}
}

func parseFrame(content string) ([][]bool, error) {
	lines := strings.Split(content, "\n")
	bitmap := make([][]bool, 24)
	lineIdx := 0
	for lineIdx < len(lines) && !strings.HasPrefix(lines[lineIdx], "===") {
		lineIdx++
	}
	if lineIdx >= len(lines) {
		return nil, fmt.Errorf("no header")
	}
	lineIdx++
	for y := 0; y < 24; y++ {
		for lineIdx < len(lines) && strings.TrimSpace(lines[lineIdx]) == "" {
			lineIdx++
		}
		if lineIdx >= len(lines) {
			return nil, fmt.Errorf("unexpected end")
		}
		line := lines[lineIdx]
		lineIdx++
		bitmap[y] = make([]bool, 24)
		x := 0
		for _, ch := range line {
			if ch == '█' || ch == '▓' {
				bitmap[y][x] = true
				x++
			} else if ch == '░' || ch == '·' || ch == ' ' {
				bitmap[y][x] = false
				x++
			}
			if x >= 24 {
				break
			}
		}
	}
	return bitmap, nil
}

func loadFrameFromFile(content string, targetFrame int) ([][]bool, error) {
	lines := strings.Split(content, "\n")
	pat := regexp.MustCompile(`=== Frame (\d+)`)
	cur := -1
	var curLines []string
	for _, line := range lines {
		if m := pat.FindStringSubmatch(line); m != nil {
			if cur == targetFrame && len(curLines) > 0 {
				return parseFrame(strings.Join(curLines, "\n"))
			}
			cur, _ = strconv.Atoi(m[1])
			curLines = []string{line}
		} else {
			curLines = append(curLines, line)
		}
	}
	if cur == targetFrame {
		return parseFrame(strings.Join(curLines, "\n"))
	}
	return nil, fmt.Errorf("not found")
}

func main() {
	// Extract from demo frames (pattern table)
	// Screen frame = Demo frame + 1 (verified offset)
	// 11 unique patterns showing one complete marching cycle (upright to upright)
	// Demo frame 337 reuses demo frame 336's upright pattern, so we show 336 twice
	demoFrames := []int{298, 320, 322, 324, 326, 328, 330, 332, 334, 336, 336}
	frameLabels := []int{299, 321, 323, 325, 327, 329, 331, 333, 335, 337, 338}

	fmt.Println("11-FRAME MARCHING CYCLE (Grid Layout)")
	fmt.Println("=====================================")
	fmt.Println("Screen frames 299-338 (demo frames 298-337, +1 offset)")
	fmt.Println()

	// Best parameters for pivot calculation (using screen frame labels)
	bestParams := map[int]struct{ cx, cy, size, angle float64 }{
		299: {12.0, 11.5, 8.0, 0.0},           // Upright (start)
		321: {11.750000, 10.875000, 8.109375, 63.50},
		323: {12.269531, 11.359375, 8.085938, 70.90},
		325: {11.597656, 11.175781, 7.914062, 81.40},
		327: {11.750000, 11.250000, 7.753906, -1.70},  // Near upright
		329: {12.250000, 11.050781, 7.988281, 11.20},
		331: {11.664062, 11.410156, 8.066406, 17.30},
		333: {11.750000, 11.023438, 8.132812, 26.60},
		335: {11.750000, 11.656250, 8.054688, -146.30},
		337: {12.0, 11.5, 8.0, 0.0},           // Upright (end)
		338: {12.0, 11.5, 8.0, 0.0},           // Upright (reuses 337)
	}

	var bitmaps [][][]bool
	var pivots [][2]float64

	// NOTE: Load from SOURCE (animation file generated by emulator), not from frames/ folder
	// Load animation file once
	animContent, err := os.ReadFile("../emulator/frames/animation_295-340.txt")
	if err != nil {
		fmt.Println("Error loading animation file:", err)
		fmt.Println("Run: cd ../emulator && go run . -no-audio -no-frames -extract-pattern='295-340' -stop-at=341")
		return
	}

	// Load frames from animation file (using demo frame numbers)
	for i, demoFrame := range demoFrames {
		fmt.Printf("Loading demo frame %d (will be labeled as screen frame %d)... ", demoFrame, frameLabels[i])
		bitmap, err := loadFrameFromFile(string(animContent), demoFrame)
		if err != nil {
			fmt.Printf("NOT FOUND\n")
			continue
		}
		fmt.Printf("OK\n")
		bitmaps = append(bitmaps, bitmap)

		// Get pivot from best params using frame label
		frameLabel := frameLabels[i]
		if params, ok := bestParams[frameLabel]; ok {
			pivots = append(pivots, [2]float64{params.cx, params.cy})
		} else {
			// Estimate pivot at center
			pivots = append(pivots, [2]float64{12.0, 11.5})
		}
	}

	fmt.Printf("Loaded %d frames\n", len(bitmaps))
	fmt.Printf("Bitmaps array length: %d, Labels array length: %d\n\n", len(bitmaps), len(frameLabels))

	// Create grid layout: 4 columns × 3 rows
	cols := 4
	rows := int(math.Ceil(float64(len(bitmaps)) / float64(cols)))
	scale := 8
	cellWidth := 30 * scale
	cellHeight := 28 * scale
	width := cols * cellWidth
	height := rows * cellHeight

	img := image.NewRGBA(image.Rect(0, 0, width, height))

	// Background
	for y := 0; y < height; y++ {
		for x := 0; x < width; x++ {
			img.Set(x, y, color.RGBA{250, 250, 255, 255})
		}
	}

	// Draw each frame in grid
	for i, bitmap := range bitmaps {
		row := i / cols
		col := i % cols
		cellX := col * cellWidth
		cellY := row * cellHeight

		// Draw cell border
		for x := 0; x < cellWidth; x++ {
			img.Set(cellX+x, cellY, color.RGBA{200, 200, 200, 255})
			img.Set(cellX+x, cellY+cellHeight-1, color.RGBA{200, 200, 200, 255})
		}
		for y := 0; y < cellHeight; y++ {
			img.Set(cellX, cellY+y, color.RGBA{200, 200, 200, 255})
			img.Set(cellX+cellWidth-1, cellY+y, color.RGBA{200, 200, 200, 255})
		}

		// Center the 24×24 frame within the cell
		offsetX := cellX + (cellWidth-24*scale)/2
		offsetY := cellY + (cellHeight-24*scale)/2

		// Draw baseline (thin red line at bottom of square area)
		baselineY := offsetY + 18*scale
		for x := offsetX; x < offsetX+24*scale; x++ {
			img.Set(x, baselineY, color.RGBA{200, 100, 100, 255})
		}

		// Draw frame content (unwrap if needed)
		hasLeft, hasRight := false, false
		for y := 0; y < 24; y++ {
			if bitmap[y][0] {
				hasLeft = true
			}
			if bitmap[y][23] {
				hasRight = true
			}
		}
		wrapped := hasLeft && hasRight

		// Find split point
		splitGap := -1
		if wrapped {
			for x := 1; x < 23; x++ {
				emptyCount := 0
				for checkX := x; checkX < 24 && emptyCount < 10; checkX++ {
					colEmpty := true
					for y := 0; y < 24; y++ {
						if bitmap[y][checkX] {
							colEmpty = false
							break
						}
					}
					if colEmpty {
						emptyCount++
					} else {
						break
					}
				}
				if emptyCount >= 5 {
					splitGap = x
					break
				}
			}
		}

		// Draw square
		for y := 0; y < 24; y++ {
			for x := 0; x < 24; x++ {
				if bitmap[y][x] {
					drawX := x
					// Unwrap: shift left part to right
					if wrapped && splitGap > 0 && x < splitGap {
						drawX = x + 24 - splitGap
					} else if wrapped && splitGap > 0 {
						drawX = x - splitGap
					}

					// Keep within cell bounds
					if drawX >= 0 && drawX < 24 {
						px := offsetX + drawX*scale
						py := offsetY + y*scale
						for dy := 0; dy < scale; dy++ {
							for dx := 0; dx < scale; dx++ {
								img.Set(px+dx, py+dy, color.RGBA{0, 0, 0, 255})
							}
						}
					}
				}
			}
		}

		// Draw pivot point (small red cross)
		pivot := pivots[i]
		pivotX := offsetX + int(pivot[0]*float64(scale))
		pivotY := offsetY + int(pivot[1]*float64(scale))
		pivotSize := 4
		for d := -pivotSize; d <= pivotSize; d++ {
			img.Set(pivotX+d, pivotY, color.RGBA{255, 0, 0, 255})
			img.Set(pivotX, pivotY+d, color.RGBA{255, 0, 0, 255})
		}

		// Draw frame number at top-left of cell
		frameNumLabel := fmt.Sprintf("%d", frameLabels[i])
		// Simple number rendering - just draw the digits in a basic way
		labelX := cellX + 5
		labelY := cellY + 10
		for _, ch := range frameNumLabel {
			if ch >= '0' && ch <= '9' {
				// Draw digit using simple 5x7 bitmap
				drawDigit(img, labelX, labelY, int(ch-'0'))
				labelX += 6
			}
		}
	}

	f, _ := os.Create("11frames_grid_layout.png")
	defer f.Close()
	png.Encode(f, img)

	fmt.Println("Created 11frames_grid_layout.png")
	fmt.Println("Layout: 4 columns × 3 rows")
	fmt.Println("Each frame centered in its cell")
	fmt.Println("Red baseline shows ground reference")
	fmt.Println("Red cross shows pivot point")
	fmt.Println("Wrapped frames are unwrapped for display")
}
