package main

import (
	"fmt"
	"os"
	"strings"
)

// sectionNames matches the section order in serializeTrackerFormat.
var sectionNames = [20]string{
	"FREQ_TABLE",
	"TOGGLE_VALS",
	"TOGGLE_IDX",
	"FREQ_MOD",
	"TONE_SEQS",
	"DELAYED_VIB",
	"SUSTAIN_PATS",
	"INSTRUMENTS",
	"DUR_TABLE",
	"REST_DURS",
	"NOTE_PATS",
	"TONE_OVERRIDES",
	"BLOCKS",
	"STREAM_A",
	"STREAM_B",
	"STREAM_C",
	"FM_OFFSETS",
	"BLOCK_LENGTHS",
	"NPT_WAVE_SEQS",
	"NPT_WAVE_OVERRIDES",
}

// sectionsNeeded lists the ROM sections the 6502 player actually reads at runtime,
// in the order they appear in the ROM. Gaps between them are dropped.
var sectionsNeeded = []int{
	0,  // FREQ_TABLE       — frequency lookup
	1,  // TOGGLE_VALS      — CIA timer periods (uint16 LE, indexed by nibble)
	2,  // TOGGLE_IDX       — nibble-packed index per freqIdx
	3,  // FREQ_MOD         — FM pattern data (header+body per pattern)
	5,  // DELAYED_VIB      — DV template data (4×uint16 per template)
	6,  // SUSTAIN_PATS     — per-note sustain bitstreams (header+body per entry)
	7,  // INSTRUMENTS      — wave/ADSR (byte 3 = sustain pat index)
	8,  // DUR_TABLE        — note durations
	9,  // REST_DURS        — rest durations
	10, // NOTE_PATS        — freqIdx + packed arrays + freqModIdx sub-array
	12, // BLOCKS           — block bodies
	13, // STREAM_A
	14, // STREAM_B
	15, // STREAM_C
	16, // FM_OFFSETS       — 1 byte per FM pattern: byte offset into FREQ_MOD
	17, // BLOCK_LENGTHS    — 1 byte per block for O(N) seek
	18, // NPT_WAVE_SEQS    — wave+toggle sequences (waveByteLen + wave_packed + frameCount + uint16×frameCount)
	19, // NPT_WAVE_OVERRIDES — (pid, seqIdx) pairs for NPT notes with toggle sequences
}

// writeTrackerASM emits a ca65-compatible .inc file containing only the sections
// needed for runtime replay. Each section is emitted contiguously with a label;
// sections not in sectionsNeeded are omitted entirely.
func writeTrackerASM(rom []byte, path string) {
	var sb strings.Builder

	sb.WriteString("; Auto-generated by tools — do not edit.\n")
	sb.WriteString("; Tracker music data for the SID player (runtime sections only).\n")
	sb.WriteString(";\n")
	sb.WriteString("; Full ROM section offsets:\n")

	offsets := [20]int{}
	for i := 0; i < 20; i++ {
		offsets[i] = int(uint16(rom[i*2]) | uint16(rom[i*2+1])<<8)
		sb.WriteString(fmt.Sprintf("; %18s = %d ($%04X)\n", sectionNames[i], offsets[i], offsets[i]))
	}
	freqModCount := int(rom[40])
	notePatCount := (offsets[11] - offsets[10] - freqModCount) / 2
	blockCount   := offsets[18] - offsets[17] // BLOCK_LENGTHS section: 1 byte per block
	sb.WriteString(fmt.Sprintf("; %14s = %d\n", "freqModCount", freqModCount))
	sb.WriteString(fmt.Sprintf("; %14s = %d\n", "notePatCount", notePatCount))
	sb.WriteString(fmt.Sprintf("; %14s = %d\n", "blockCount", blockCount))
	sb.WriteString(";\n")


	sb.WriteString(".segment \"RODATA\"\n\n")

	// sectionEnd returns the byte offset one past the end of section i in the ROM.
	// For the last section in the ROM, it uses len(rom).
	sectionEnd := func(i int) int {
		// find next section that has a higher offset
		for j := i + 1; j < 20; j++ {
			if offsets[j] > offsets[i] {
				return offsets[j]
			}
		}
		return len(rom)
	}

	// Build a set of needed sections for quick lookup.
	needed := make(map[int]bool, len(sectionsNeeded))
	for _, s := range sectionsNeeded {
		needed[s] = true
	}

	flushBytes := func(data []byte, label string) {
		sb.WriteString(label + ":\n")
		for i := 0; i < len(data); i += 16 {
			end := i + 16
			if end > len(data) {
				end = len(data)
			}
			sb.WriteString(".byte ")
			for j := i; j < end; j++ {
				if j > i {
					sb.WriteString(",")
				}
				sb.WriteString(fmt.Sprintf("$%02X", data[j]))
			}
			sb.WriteString("\n")
		}
	}

	nptOverrideCount := (sectionEnd(19) - offsets[19]) / 2

	totalBytes := 0
	for _, s := range sectionsNeeded {
		start := offsets[s]
		end := sectionEnd(s)
		slice := rom[start:end]
		label := fmt.Sprintf("MUSIC_%s", sectionNames[s])
		flushBytes(slice, label)
		totalBytes += len(slice)
		if s == 10 {
			sb.WriteString(fmt.Sprintf("NOTE_PAT_FREQ_BASE = MUSIC_NOTE_PATS\n"))
			sb.WriteString(fmt.Sprintf("NOTE_PAT_PACK_BASE = MUSIC_NOTE_PATS + %d\n", notePatCount))
			sb.WriteString(fmt.Sprintf("NOTE_PAT_FM_BASE = MUSIC_NOTE_PATS + %d\n", notePatCount*2))
			sb.WriteString(fmt.Sprintf("MUSIC_FREQ_MOD_COUNT = %d\n", freqModCount))
			sb.WriteString(fmt.Sprintf("MUSIC_BLOCK_COUNT = %d\n", blockCount))
		}
		if s == 13 || s == 14 || s == 15 {
			chLetter := string(rune('A' + s - 13))
			sb.WriteString(fmt.Sprintf("MUSIC_STREAM_%s_END = MUSIC_STREAM_%s + %d\n", chLetter, chLetter, len(slice)))
		}
		if s == 19 {
			sb.WriteString(fmt.Sprintf("MUSIC_NPT_OVR_COUNT = %d\n", nptOverrideCount))
		}
	}

	if err := os.WriteFile(path, []byte(sb.String()), 0644); err != nil {
		panic(fmt.Sprintf("writeTrackerASM: %v", err))
	}
	fmt.Printf("✓ Music ASM written to: %s (%d bytes, %d bytes omitted)\n",
		path, totalBytes, len(rom)-38-totalBytes)
}
