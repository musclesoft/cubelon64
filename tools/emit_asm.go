package main

import (
	"fmt"
	"os"
	"strings"
)

// sectionNames matches the section order in serializeTrackerFormat.
var sectionNames = [16]string{
	"FREQ_TABLE",
	"TOGGLE_VALS",
	"TOGGLE_IDX",
	"FREQ_MOD",
	"TONE_SEQS",
	"DELAYED_VIB",
	"SUSTAIN_PATS",
	"INSTRUMENTS",
	"DUR_TABLE",
	"REST_DURS",
	"NOTE_PATS",
	"TONE_OVERRIDES",
	"BLOCKS",
	"STREAM_A",
	"STREAM_B",
	"STREAM_C",
}

// writeTrackerASM emits a ca65-compatible .inc file containing the serialized
// tracker ROM as a labelled byte table plus .equ constants for each section offset.
// The offsets are relative to the MUSIC_DATA label so the player can be loaded
// at any address and compute absolute addresses at link time.
func writeTrackerASM(rom []byte, path string) {
	var sb strings.Builder

	sb.WriteString("; Auto-generated by tools — do not edit.\n")
	sb.WriteString("; Tracker music data for the SID player.\n")
	sb.WriteString(";\n")
	sb.WriteString("; Section offsets (relative to MUSIC_DATA):\n")

	// Read the 16 uint16 section offsets from the ROM header.
	for i := 0; i < 16; i++ {
		off := int(uint16(rom[i*2]) | uint16(rom[i*2+1])<<8)
		sb.WriteString(fmt.Sprintf("; %14s = %d ($%04X)\n", sectionNames[i], off, off))
	}
	freqModCount := int(rom[32])
	sb.WriteString(fmt.Sprintf("; %14s = %d\n", "freqModCount", freqModCount))
	sb.WriteString(fmt.Sprintf("; Total size = %d bytes\n", len(rom)))
	sb.WriteString("\n")

	sb.WriteString(".segment \"RODATA\"\n\n")

	// Section offset .equ constants so the player can reference by name.
	for i := 0; i < 16; i++ {
		off := int(uint16(rom[i*2]) | uint16(rom[i*2+1])<<8)
		sb.WriteString(fmt.Sprintf("MUSIC_%-16s = MUSIC_DATA + %d\n", sectionNames[i], off))
	}
	sb.WriteString(fmt.Sprintf("MUSIC_FREQ_MOD_COUNT    = %d\n", freqModCount))
	sb.WriteString("\n")

	// Raw data as .byte directives, 16 bytes per line.
	sb.WriteString("MUSIC_DATA:\n")
	const stride = 16
	for i := 0; i < len(rom); i += stride {
		end := i + stride
		if end > len(rom) {
			end = len(rom)
		}
		sb.WriteString(".byte ")
		for j := i; j < end; j++ {
			if j > i {
				sb.WriteString(",")
			}
			sb.WriteString(fmt.Sprintf("$%02X", rom[j]))
		}
		sb.WriteString("\n")
	}

	if err := os.WriteFile(path, []byte(sb.String()), 0644); err != nil {
		panic(fmt.Sprintf("writeTrackerASM: %v", err))
	}
	fmt.Printf("✓ Music ASM written to: %s (%d bytes ROM)\n", path, len(rom))
}
